#!/usr/bin/env python3
"""Generate secp256k1_tables.zig: affine generator multiples as little-endian u64 limbs.

python3 zig/src/protocol/secp256k1_tables_gen.py > zig/src/protocol/secp256k1_tables.zig
The Zig tests recompute every entry with std.crypto arithmetic, so this script is
a convenience, not a trust root.
"""
P = 2**256 - 2**32 - 977
G = (55066263022277343669578718895168534326250603453777594175500187360389116729240,
     32670510020758816978083085130507043184471273380659243275938904335757337482424)


def add(p, q):
    if p is None:
        return q
    if p[0] == q[0]:
        assert p[1] == q[1]
        lam = 3 * p[0] * p[0] * pow(2 * p[1], -1, P) % P
    else:
        lam = (q[1] - p[1]) * pow(q[0] - p[0], -1, P) % P
    x = (lam * lam - p[0] - q[0]) % P
    return x, (lam * (p[0] - x) - p[1]) % P


def mul(k, p):
    acc = None
    while k:
        if k & 1:
            acc = add(acc, p)
        p = add(p, p)
        k >>= 1
    return acc


def limbs(v):
    return ", ".join("0x%016x" % ((v >> (64 * i)) & (2**64 - 1)) for i in range(4))


def point(p):
    return ".{ .{ %s }, .{ %s } }," % (limbs(p[0]), limbs(p[1]))


print("//! Generated by secp256k1_tables_gen.py; verified by secp256k1.zig tests.")
print("/// Affine x and y, canonical, little-endian 64-bit limbs.")
print("pub const Entry = [2][4]u64;")
print()
print("/// comb[i][j] = (j + 1) * 16^i * G for signed 4-bit windows (65 windows).")
print("pub const comb: [65][8]Entry = .{")
base = G
for i in range(65):
    print("    .{")
    acc = None
    for j in range(8):
        acc = add(acc, base)
        print("        " + point(acc))
    print("    },")
    base = mul(16, base)
print("};")
print()
print("/// odd[j] = (2j + 1) * G, for width-8 wNAF.")
print("pub const odd: [64]Entry = .{")
two_g = add(G, G)
acc = G
for j in range(64):
    print("    " + point(acc))
    acc = add(acc, two_g)
print("};")
