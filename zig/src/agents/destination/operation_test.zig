test "Native destination inherited Rust payload relations block fresh staging signing and rebroadcast but permit independent finalized delivery" {
    const a = std.testing.allocator;
    var temp = std.testing.tmpDir(.{});
    defer temp.cleanup();
    const base = try temp.dir.realpathAlloc(a, ".");
    defer a.free(base);
    const path = try std.fs.path.join(a, &.{ base, "native" });
    defer a.free(path);
    var database = try db.rocks.Database.open(a, path, .{});
    defer database.deinit();
    var origin = store.Store.init(a, &database, "origin");
    const message: protocol.Message = .{ .nonce = 0, .origin = 1, .destination = 2, .sender = .{1} ** 32, .recipient = .{2} ** 32, .body = "Source Lander migration" };
    _ = try origin.storeMessage(message, 1, null);
    const options: Options = .{ .id = message.id(), .context = .{7} ** 32, .nonce = 0, .origin = 1, .destination = 2, .policy = .{ .confirm_delay_ms = 0 } };
    const now: Times = .{ .unix_ms = 1000, .monotonic_ms = 0 };
    const uuids = try db.codec.encodeUuids(a, &.{.{3} ** 16});
    defer a.free(uuids);
    try inheritedFixture(&origin, message.id(), uuids);
    var actor = try Operation.open(a, &origin, options, now);
    try std.testing.expect(try actor.hasInheritedPayloads());
    try inheritedFixture(&origin, message.id(), &.{0});
    try std.testing.expectError(error.TruncatedRecord, actor.hasInheritedPayloads());
    try std.testing.expectError(error.TruncatedRecord, actor.tick(now));
    try inheritedFixture(&origin, message.id(), uuids);
    try std.testing.expectError(error.InheritedPayloadNeedsReconciliation, actor.tick(now));
    try std.testing.expectEqual(@as(u64, 0), actor.value.generation);
    try std.testing.expect((try origin.status(message.id())) == null);
    actor.deinit();
    actor = try Operation.open(a, &origin, options, now);
    defer actor.deinit();
    try std.testing.expectError(error.InheritedPayloadNeedsReconciliation, actor.tick(now));
    // Fixture-only explicit reconciler removes a terminal Source relation.
    // Production has no automatic receipt-absence/delete escape hatch.
    try inheritedFixture(&origin, message.id(), null);
    try std.testing.expectEqual(Effect{ .prepare = 1 }, try actor.tick(now));
    var prepared_value = try types.Prepared.init(a, .{ .protocol = .tron, .origin = 1, .destination = 2, .mailbox = .{3} ** 32, .chain_id = "fixture", .operation_id = message.id(), .generation = 1 }, "{\"fixture\":true}", 1, 2);
    defer prepared_value.deinit();
    try actor.prepared(&prepared_value, true, true, now);
    try inheritedFixture(&origin, message.id(), uuids);
    try std.testing.expectError(error.InheritedPayloadNeedsReconciliation, actor.persistence(now).intent(&prepared_value));
    try inheritedFixture(&origin, message.id(), null);
    var signed = try types.Signed.init(a, .{ .hash256 = .{4} ** 32 }, "exact Source migration guarded signed bytes");
    defer signed.deinit();
    try actor.persistence(now).signed(&prepared_value, &signed);
    try inheritedFixture(&origin, message.id(), uuids);
    try std.testing.expectError(error.InheritedPayloadNeedsReconciliation, actor.persistence(now).signed(&prepared_value, &signed));
    try std.testing.expectError(error.InheritedPayloadNeedsReconciliation, actor.rebroadcast(now));
    // Do not strand already-delivered messages merely because Source retained
    // historical relations. Finalized mailbox state is independent evidence.
    try actor.alreadyDelivered(true, now);
    try std.testing.expect(try origin.processed(0));
    try std.testing.expect(try actor.hasInheritedPayloads());
    const retained = (try origin.typed.get(a, db.keys.Table.payload_uuids_by_message_id.prefix(), &message.id())).?;
    defer a.free(retained);
    try std.testing.expectEqualSlices(u8, uuids, retained);
}
fn inheritedFixture(origin: *store.Store, id: [32]u8, relation: ?[]const u8) !void {
    var batch = try origin.typed.batch(origin.allocator);
    defer batch.deinit();
    const key = db.keys.Table.payload_uuids_by_message_id.prefix();
    if (relation) |bytes| try batch.put(key, &id, bytes) else try batch.delete(key, &id);
    try batch.commitSync();
}

