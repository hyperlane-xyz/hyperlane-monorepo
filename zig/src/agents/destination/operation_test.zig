test "Native destination operation recovers full512bit identity and commits Rust delivery markers atomically" {
    const a = std.testing.allocator;
    var temp = std.testing.tmpDir(.{});
    defer temp.cleanup();
    const base = try temp.dir.realpathAlloc(a, ".");
    defer a.free(base);
    const path = try std.fs.path.join(a, &.{ base, "native" });
    defer a.free(path);
    var database = try db.rocks.Database.open(a, path, .{});
    defer database.deinit();
    var origin = store.Store.init(a, &database, "origin");
    const message: protocol.Message = .{ .version = 3, .nonce = 0, .origin = 1, .destination = 2, .sender = .{1} ** 32, .recipient = .{2} ** 32, .body = "native durability" };
    _ = try origin.storeMessage(message, 10, null);
    const options: Options = .{ .id = message.id(), .context = .{7} ** 32, .nonce = 0, .origin = 1, .destination = 2, .policy = .{ .confirm_delay_ms = 0 } };
    const now: Times = .{ .unix_ms = 1000, .monotonic_ms = 0 };
    var operation = try Operation.open(a, &origin, options, now);
    try std.testing.expectEqual(Effect{ .prepare = 1 }, try operation.tick(now));
    var prepared_value = try types.Prepared.init(a, .{ .protocol = .sealevel, .origin = 1, .destination = 2, .mailbox = .{3} ** 32, .chain_id = "fixture", .operation_id = message.id(), .generation = 1 }, "{\"fixture\":true}", 100, 200);
    defer prepared_value.deinit();
    try operation.prepared(&prepared_value, true, true, now);
    const gate = operation.persistence(now);
    try gate.intent(&prepared_value);
    try gate.persistAuthorization.?(gate.context, message.id(), "{\"signed_authorization\":true}");
    const identity: types.Identity = .{ .signature512 = .{0xab} ** 32 ++ .{0xcd} ** 32 };
    var signed = try types.Signed.init(a, identity, &.{ 0xff, 0xfe, 1, 0, 2 });
    defer signed.deinit();
    try gate.signed(&prepared_value, &signed);
    operation.deinit(); // Crash before the returned exact signature is submitted.
    operation = try Operation.open(a, &origin, options, .{ .unix_ms = 2000, .monotonic_ms = 100 });
    defer operation.deinit();
    try std.testing.expectEqual(Effect{ .reconcile = identity }, try operation.tick(.{ .unix_ms = 2000, .monotonic_ms = 100 }));
    try std.testing.expectEqualSlices(u8, signed.bytes, operation.signed.?.bytes);
    try std.testing.expectEqualStrings("{\"signed_authorization\":true}", operation.authorization.?);
    try std.testing.expectEqual(db.json.Status.ReadyToSubmit, (try origin.status(message.id())).?);
    var receipt: types.Receipt = .{ .identity = identity, .block_hash = .{8} ** 32, .height = 20, .success = true, .finalized = false, .expenditure = .{ .gas_used = 123, .tokens_used = 456 } };
    try std.testing.expectError(error.FinalizedNativeReceiptRequired, operation.recordExpenditure(receipt));
    receipt.finalized = true;
    try std.testing.expect(try operation.recordExpenditure(receipt));
    try std.testing.expect(!try operation.recordExpenditure(receipt));
    operation.deinit(); // Accounting committed; crash before delivery marker.
    operation = try Operation.open(a, &origin, options, .{ .unix_ms = 2001, .monotonic_ms = 101 });
    try std.testing.expect(!try operation.recordExpenditure(receipt));
    try std.testing.expectEqual(@as(u256, 123), (try origin.expenditure(message.id())).gas_used);
    try std.testing.expectEqual(@as(u256, 456), (try origin.expenditure(message.id())).tokens_used);
    receipt.expenditure.?.gas_used += 1;
    try std.testing.expectError(error.ConflictingNativeExpenditure, operation.recordExpenditure(receipt));
    try operation.observe(false, true, now);
    try std.testing.expect(!try origin.processed(message.nonce));
    try operation.observe(true, true, now);
    try std.testing.expect(try origin.processed(message.nonce));
    try std.testing.expect((try origin.pendingAtOrAfter(message.destination, 0)) == null);
    const wrong: Options = .{ .id = options.id, .context = .{8} ** 32, .nonce = 0, .origin = 1, .destination = 2, .policy = .{ .confirm_delay_ms = 0 } };
    try std.testing.expectError(error.OperationContextChanged, Operation.open(a, &origin, wrong, now));
}
