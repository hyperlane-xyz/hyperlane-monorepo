const std = @import("std");
const db = @import("../../db/root.zig");
const protocol = @import("../../protocol/root.zig");
const queue = @import("reveal_queue.zig");
const reveal = @import("reveal.zig");
test "UR reveal queue survives replay rotates routes CAS guards edits and scopes new cycles without process markers" {
    const a = std.testing.allocator;
    var temp = std.testing.tmpDir(.{});
    defer temp.cleanup();
    const base = try temp.dir.realpathAlloc(a, ".");
    defer a.free(base);
    const path = try std.fs.path.join(a, &.{ base, "native" });
    defer a.free(path);
    var database = try db.rocks.Database.open(a, path, .{});
    defer database.deinit();
    var store = @import("../store.zig").Store.init(a, &database, "origin");
    var body: [96]u8 = .{1} ** 96;
    const message: protocol.Message = .{ .origin = 1, .destination = 2, .nonce = 0, .sender = .{2} ** 32, .recipient = .{3} ** 32, .body = &body };
    const commit = reveal.Commit.message(.{3} ** 32, message).?;
    const context = [_]u8{4} ** 32;
    try std.testing.expect(try queue.enqueue(a, &store, context, .{5} ** 32, message, commit, .reveal));
    try std.testing.expect(!try queue.enqueue(a, &store, context, .{5} ** 32, message, commit, .reveal));
    var first = (try queue.next(a, &store, 2)).?;
    defer first.deinit();
    try std.testing.expectEqual(@as(u64, 0), first.value().cycle);
    var owned = try first.message();
    defer owned.deinit();
    try std.testing.expectEqual(message.id(), owned.value.id());
    try std.testing.expect(!try store.processed(message.nonce));
    try std.testing.expect((try store.status(message.id())) == null);
    var stale = (try queue.next(a, &store, 2)).?;
    defer stale.deinit();
    first.value().phase = .tokens;
    first.schedule(1000, 5000);
    try first.setSignature(.{6} ** 65);
    try first.save();
    stale.value().phase = .prepare;
    try std.testing.expectError(error.StaleRevealQueueRow, stale.save());
    var restored = (try queue.next(a, &store, 2)).?;
    defer restored.deinit();
    try std.testing.expectEqual(queue.Phase.tokens, restored.value().phase);
    try std.testing.expect(!restored.due(5999) and restored.due(6000));
    try std.testing.expect(restored.value().signature_hex != null);
    restored.value().phase = .done;
    try restored.save();
    try std.testing.expect((try queue.next(a, &store, 2)) == null);
    try std.testing.expect(!try queue.enqueue(a, &store, context, .{7} ** 32, message, commit, .reveal));
    var next = message;
    next.nonce = 1;
    try std.testing.expect(try queue.enqueue(a, &store, context, .{7} ** 32, next, reveal.Commit.message(.{3} ** 32, next).?, .reveal));
    var cycle = (try queue.next(a, &store, 2)).?;
    defer cycle.deinit();
    try std.testing.expectEqual(@as(u64, 1), cycle.value().cycle);
    try std.testing.expect(!std.mem.eql(u8, cycle.value().operation_hex, first.value().operation_hex));
    try std.testing.expectError(error.RevealContextChanged, queue.enqueue(a, &store, .{8} ** 32, .{7} ** 32, next, reveal.Commit.message(.{3} ** 32, next).?, .reveal));
    body[0] = 9;
    var other = message;
    other.body = &body;
    try std.testing.expect(try queue.enqueue(a, &store, context, .{7} ** 32, other, reveal.Commit.message(.{3} ** 32, other).?, .reveal));
    var one = (try queue.next(a, &store, 2)).?;
    defer one.deinit();
    var two = (try queue.next(a, &store, 2)).?;
    defer two.deinit();
    try std.testing.expect(!std.mem.eql(u8, &one.route, &two.route));
    try std.testing.expect((try queue.next(a, &store, 3)) == null);
}
