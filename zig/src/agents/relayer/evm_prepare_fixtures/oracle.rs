extern crate ethers;

use ethers::core::utils::__serde_json as serde_json;
use ethers::abi::{Function, Token};
use ethers::types::transaction::eip2718::TypedTransaction;
use ethers::types::{Bytes, NameOrAddress, TransactionRequest, H160, H256, U64};

mod mailbox_abi {
    include!("../../../../../rust/main/chains/hyperlane-ethereum/src/interfaces/i_mailbox.rs");
}
use mailbox_abi::i_mailbox::IMAILBOX_ABI;

fn chunks(value: &serde_json::Value) -> serde_json::Value {
    let text = serde_json::to_string(value).unwrap();
    let parts: Vec<String> = text.as_bytes().chunks(32).map(|part| String::from_utf8(part.to_vec()).unwrap()).collect();
    serde_json::to_value(parts).unwrap()
}

fn main() {
    let process = IMAILBOX_ABI.function("process").unwrap().clone();
    let delivered = IMAILBOX_ABI.function("delivered").unwrap().clone();
    let message = ethers::utils::hex::decode(concat!(
        "0300000007000003e800000000000000",
        "00000000000000000000000000000000",
        "000000000000000001000007d0ff0000",
        "00000000000000000022222222222222",
        "22222222222222222222222222112233"
    )).unwrap();
    let message_id = H256::from(ethers::utils::keccak256(&message));
    let metadata = vec![0xab, 0xcd];
    let data = process.encode_input(&[Token::Bytes(metadata), Token::Bytes(message)]).unwrap();
    let mailbox = H160::from_low_u64_be(0x42);
    let process_tx = TypedTransaction::Legacy(TransactionRequest {
        to: Some(NameOrAddress::Address(mailbox)),
        data: Some(Bytes::from(data)),
        chain_id: Some(U64::from(31337)),
        ..Default::default()
    });
    let delivered_data = delivered.encode_input(&[Token::FixedBytes(message_id.as_bytes().to_vec())]).unwrap();
    let delivered_tx = TypedTransaction::Legacy(TransactionRequest {
        to: Some(NameOrAddress::Address(mailbox)),
        data: Some(Bytes::from(delivered_data)),
        ..Default::default()
    });
    let process_pair = serde_json::to_value((&process_tx, Function::from(process))).unwrap();
    let delivered_pair = serde_json::to_value((&delivered_tx, Function::from(delivered))).unwrap();
    println!("{}", serde_json::to_string_pretty(&serde_json::json!({
        "process": chunks(&process_pair),
        "delivered": chunks(&delivered_pair),
        "note": "Generated by unchanged Rust IMAILBOX_ABI and ethers 1.0.2 serde; chunks are <=32 bytes."
    })).unwrap());
}
