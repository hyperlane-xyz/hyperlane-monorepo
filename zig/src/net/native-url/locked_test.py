"""Pure lock/notice controls; no Cargo, registry, role or network execution."""
import gzip
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location('url_locked', Path(__file__).with_name('locked.py'))
API = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(API)


class LockedTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory(prefix='ziggy-url-locked-pure-')
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name).resolve()
        self.base = self.root / 'native-url'
        self.base.mkdir()
        self.target = self.root / 'configured-target'
        (self.target / 'release').mkdir(parents=True)
        self.package = self.root / 'registry-package'
        self.package.mkdir()
        self.text = b'Exact public fixture notice\n'
        (self.package / 'LICENSE-MIT').write_bytes(self.text)
        self.metadata = {'target_directory': str(self.target), 'packages': [{'name': 'public-fixture', 'version': '1.0.0', 'source': 'registry+public-fixture', 'license': 'MIT', 'license_file': None, 'manifest_path': str(self.package / 'Cargo.toml')}, {'name': 'missing-fixture', 'version': '1.0.0', 'source': None, 'license': None, 'license_file': None, 'manifest_path': str(self.base / 'Cargo.toml')}]}

    def notices(self, target=None):
        with patch.object(API, 'BASE', self.base), patch.object(API.subprocess, 'check_output', return_value=json.dumps(self.metadata).encode()):
            return API.licenses('fixture-toolchain-never-executed', target)

    def test_configured_target_exact_text_missing_notice_and_idempotence(self):
        output = self.notices()
        self.assertEqual(output, self.target / 'release/ziggy-url-licenses')
        self.assertEqual((output / 'public-fixture-1.0.0/LICENSE-MIT').read_bytes(), self.text)
        rows = json.loads((output / 'manifest.json').read_text())
        self.assertTrue(rows[0]['missing_license_text'])
        self.assertIsNone(rows[0]['spdx'])
        before = {str(p.relative_to(output)): p.read_bytes() for p in output.rglob('*') if p.is_file()}
        self.assertEqual(self.notices(), output)
        self.assertEqual(before, {str(p.relative_to(output)): p.read_bytes() for p in output.rglob('*') if p.is_file()})

    def test_explicit_target_wins_over_configured_metadata(self):
        target = self.root / 'explicit'
        (target / 'release').mkdir(parents=True)
        self.assertEqual(self.notices(target), target / 'release/ziggy-url-licenses')
        self.assertFalse((self.target / 'release/ziggy-url-licenses').exists())

    def test_changed_existing_manifest_is_not_overwritten(self):
        output = self.notices()
        manifest = output / 'manifest.json'
        modified = manifest.read_bytes() + b'\n'
        manifest.write_bytes(modified)
        with self.assertRaisesRegex(ValueError, 'differs'):
            self.notices()
        self.assertEqual(modified, manifest.read_bytes())

    def test_source_and_output_symlinks_write_nothing_outside(self):
        outside = self.root / 'outside'
        outside.mkdir()
        marker = outside / 'marker'
        marker.write_bytes(b'unchanged')
        link = self.package / 'NOTICE'
        link.symlink_to(marker)
        with self.assertRaisesRegex(ValueError, 'symlink'):
            self.notices()
        link.unlink()
        (self.target / 'release/ziggy-url-licenses').symlink_to(outside)
        with self.assertRaisesRegex(ValueError, 'symlink'):
            self.notices()
        self.assertEqual(list(outside.iterdir()), [marker])
        self.assertEqual(marker.read_bytes(), b'unchanged')

    def test_restore_only_never_invokes_cargo_and_rejects_changed_raw_lock(self):
        wire = b'# This file is automatically @generated by Cargo.\nversion = 4\n'
        (self.base / 'Cargo.lock.gz').write_bytes(gzip.compress(wire, mtime=0))
        with patch.object(API, 'BASE', self.base), patch.object(API.subprocess, 'run', side_effect=AssertionError('Cargo forbidden')), patch('sys.argv', ['locked.py', '--restore-only']):
            API.main()
            self.assertEqual((self.base / 'Cargo.lock').read_bytes(), wire)
            (self.base / 'Cargo.lock').write_bytes(b'preserve-different-lock')
            with self.assertRaisesRegex(ValueError, 'differs'):
                API.main()
            self.assertEqual((self.base / 'Cargo.lock').read_bytes(), b'preserve-different-lock')

    def test_lock_and_license_reads_are_bounded(self):
        (self.base / 'Cargo.lock.gz').write_bytes(gzip.compress(b'x' * (API.MAXIMUM_LOCK_BYTES + 1), mtime=0))
        with patch.object(API, 'BASE', self.base), self.assertRaises(ValueError):
            API.restore()
        with (self.package / 'LICENSE-LARGE').open('wb') as stream:
            stream.truncate(8 * 1024 * 1024 + 1)
        with self.assertRaisesRegex(ValueError, 'bounded copy'):
            self.notices()
        self.assertFalse((self.target / 'release/ziggy-url-licenses').exists())


if __name__ == '__main__':
    unittest.main()
