#!/usr/bin/env python3
"""Restore this crate's exact packed lock, then build only its URL host ABI."""
import argparse
import importlib.util
import os
import gzip
import hashlib
import json
from pathlib import Path
import platform
import subprocess

_CPU_SPEC = importlib.util.spec_from_file_location("retained_cpu", Path(__file__).resolve().parents[3] / "tools/build_cpu.py")
cpu = importlib.util.module_from_spec(_CPU_SPEC)
_CPU_SPEC.loader.exec_module(cpu)

BASE = Path(__file__).resolve().parent
MAXIMUM_LOCK_BYTES = 1024 * 1024


def restore():
    with gzip.open(BASE / 'Cargo.lock.gz', 'rb') as stream:
        wire = stream.read(MAXIMUM_LOCK_BYTES + 1)
    if len(wire) > MAXIMUM_LOCK_BYTES or not wire.startswith(b'# This file is automatically @generated by Cargo.'):
        raise ValueError('Invalid packed dependency lock')
    target = BASE / 'Cargo.lock'
    if target.is_symlink():
        raise ValueError('Dependency lock must not be a symlink')
    if target.exists():
        if not target.is_file() or target.read_bytes() != wire:
            raise ValueError('Existing raw dependency lock differs from packed lock')
    else:
        with target.open('xb') as stream:
            stream.write(wire)
    return target


def licenses(toolchain, target):
    command = ['cargo', f'+{toolchain}', 'metadata', '--locked', '--offline', '--format-version', '1', '--manifest-path', str(BASE / 'Cargo.toml')]
    metadata = json.loads(subprocess.check_output(command))
    payloads = {}
    records = []
    for package in sorted(metadata['packages'], key=lambda item: (item['name'], item['version'])):
        directory = Path(package['manifest_path']).parent.resolve(strict=True)
        folder = package['name'] + '-' + package['version']
        if Path(folder).name != folder:
            raise ValueError('Unsafe package identity')
        candidates = {p for p in directory.iterdir() if p.name.upper().startswith(('LICENSE', 'COPYING', 'NOTICE', 'COPYRIGHT'))}
        if package.get('license_file'):
            candidates.add(directory / package['license_file'])
        files = []
        for path in sorted(candidates):
            if path.is_symlink():
                raise ValueError('License symlink rejected')
            if not path.is_file():
                continue
            resolved = path.resolve(strict=True)
            if not resolved.is_relative_to(directory):
                raise ValueError('License escaped its package')
            with resolved.open('rb') as stream:
                wire = stream.read(8 * 1024 * 1024 + 1)
            if len(wire) > 8 * 1024 * 1024:
                raise ValueError('License file exceeds bounded copy')
            name = str(resolved.relative_to(directory))
            destination = str(Path(folder) / name)
            payloads[destination] = wire
            files.append({'file': name, 'bytes': len(wire), 'sha256': hashlib.sha256(wire).hexdigest()})
        records.append({'package': package['name'], 'version': package['version'], 'source': package.get('source'), 'spdx': package.get('license'), 'files': files, 'missing_license_text': not files})
    payloads['manifest.json'] = (json.dumps(records, indent=2, sort_keys=True) + '\n').encode()
    target = (target or Path(metadata['target_directory'])).resolve(strict=True)
    release = target / 'release'
    output = release / 'ziggy-url-licenses'
    if release.is_symlink() or output.is_symlink():
        raise ValueError('License output parent must not be a symlink')
    if output.exists():
        if not output.is_dir():
            raise ValueError('License output is not a directory')
        existing = list(output.rglob('*'))
        if any(p.is_symlink() for p in existing):
            raise ValueError('Existing license output contains a symlink')
        if {str(p.relative_to(output)) for p in existing if p.is_file()} != set(payloads):
            raise ValueError('Existing license output differs from this exact graph')
        if any((output / name).read_bytes() != wire for name, wire in payloads.items()):
            raise ValueError('Existing license content differs')
        return output
    output.mkdir()
    for name, wire in payloads.items():
        path = output / name
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open('xb') as stream:
            stream.write(wire)
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cpu-recipe-output', type=Path)
    parser.add_argument('--toolchain', default='1.98.0')
    parser.add_argument('--offline', action='store_true')
    parser.add_argument('--restore-only', action='store_true')
    parser.add_argument('--target-dir', type=Path)
    args = parser.parse_args()
    cpu_source_before = Path(cpu.__file__).read_bytes()
    if args.cpu_recipe_output and (platform.system() != "Linux" or platform.machine() != "x86_64"):
        raise ValueError("Portable retained CPU recipe requires Linux x86_64")
    restore()
    if args.restore_only:
        return
    command = ['cargo', f'+{args.toolchain}', 'build', '--locked', '--release', '--manifest-path', str(BASE / 'Cargo.toml')]
    if args.offline:
        command.append('--offline')
    if args.target_dir:
        command += ['--target-dir', str(args.target_dir)]
    environment = cpu.portable_environment(os.environ) if args.cpu_recipe_output else dict(os.environ)
    recipe = cpu.recipe('rust', command, environment, Path(__file__)) if args.cpu_recipe_output else None
    completed = subprocess.run(command, check=True, env=environment)
    if recipe is not None:
        if Path(cpu.__file__).read_bytes() != cpu_source_before: raise ValueError("CPU compiler procedure changed")
        args.cpu_recipe_output.parent.mkdir(parents=True, exist_ok=True)
        with args.cpu_recipe_output.open('x') as stream: json.dump(cpu.finish_recipe(recipe, {'actual_parent_wait': True, 'exit_code': completed.returncode, 'error': None}), stream)
    output = licenses(args.toolchain, args.target_dir)
    filename = 'libziggy_url.dylib' if platform.system() == 'Darwin' else 'libziggy_url.so'
    print(output.parent / filename)


if __name__ == '__main__':
    main()
